export function buildSeedPayrollRun(employees: Employee[]): PayrollRun {
  const items = employees.map((emp) => calculateEmployeePayslip(emp, 0, 0));
  const totalGrossUSD = Math.round(
    items.reduce((acc, item) => acc + item.grossSalary * FX_TO_USD[item.currency], 0)
  );
  const totalNetUSD = Math.round(
    items.reduce((acc, item) => acc + item.netSalary * FX_TO_USD[item.currency], 0)
  );
  return {
    id: "pr-2026-11",
    period: "2026-11",
    label: "November 2026 Global Payroll Cycle",
    runDate: "2026-11-24T02:00:00Z",
    status: "Completed",
    totalEmployees: items.length,
    totalGrossUSD,
    totalNetUSD,
    items,
  };
}

